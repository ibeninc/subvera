"""
Builds the Subvera logo from one geometry:
  - wordmark: Space Grotesk Bold outlines (the original wordmark's typeface), tracked to match it
  - mark: navy disc with tide-line waves, drawn as quadratic curves in a 100x100 box
Writes TS geometry for the <Logo> component, standalone SVGs, PNG icons and previews.
Usage: python scripts/build-logo.py <project_root> <preview_dir>
Needs: pip install fonttools brotli pillow, and a prior `next build` or `next dev` run so the
Space Grotesk font file exists under .next/static/media.
"""
import glob, json, math, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from PIL import Image, ImageDraw

ROOT, S = sys.argv[1], sys.argv[2]


def find_font():
    """The latin Space Grotesk variable font that next/font downloaded (file names are hashed)."""
    for path in glob.glob(f"{ROOT}/.next/static/media/*.woff2"):
        t = TTFont(path)
        cmap = t.getBestCmap() or {}
        if t["name"].getDebugName(1).startswith("Space Grotesk") and all(ord(c) in cmap for c in "Subvera"):
            return path
    sys.exit("Space Grotesk not found under .next/static/media. Run the app once so next/font downloads it.")


FONT = find_font()

NAVY, DEEP, WHITE = "#0e2a47", "#143a63", "#ffffff"
WAVES = ["#14b8a6", "#13a69a", "#12938d"]  # >= 3:1 on navy and on deep blue

# ---------- mark geometry (100 x 100 box) ----------
# full: three waves, two periods. small (icons <= 24px): two thicker waves, one and a half periods.
MARKS = {
    "full": {"stroke": 4.6, "amp": 7.2, "x0": 17, "x1": 83, "halves": 4, "ys": [36, 50, 64], "colors": WAVES},
    "small": {"stroke": 7.6, "amp": 11, "x0": 19, "x1": 81, "halves": 3, "ys": [39.5, 60.5], "colors": [WAVES[0], WAVES[2]]},
}


def wave_d(m, y):
    h = (m["x1"] - m["x0"]) / m["halves"]
    d = f"M{m['x0']} {y} Q{m['x0'] + h / 2:g} {y - m['amp']:g} {m['x0'] + h:g} {y}"
    for i in range(2, m["halves"] + 1):
        d += f" T{m['x0'] + h * i:g} {y}"
    return d


def wave_points(m, y, n=80):
    """Sample the same quadratic chain for raster rendering."""
    h = (m["x1"] - m["x0"]) / m["halves"]
    pts = []
    for i in range(m["halves"]):
        sx, ex = m["x0"] + h * i, m["x0"] + h * (i + 1)
        cy = y - m["amp"] if i % 2 == 0 else y + m["amp"]
        cx = (sx + ex) / 2
        for k in range(n + 1):
            t = k / n
            x = (1 - t) ** 2 * sx + 2 * (1 - t) * t * cx + t * t * ex
            yy = (1 - t) ** 2 * y + 2 * (1 - t) * t * cy + t * t * y
            pts.append((x, yy))
    return pts


# ---------- wordmark from Space Grotesk Bold ----------
f = TTFont(FONT)
f.flavor = None
instantiateVariableFont(f, {"wght": 700}, inplace=True)
gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f["hmtx"]
upm = f["head"].unitsPerEm
cap = f["OS/2"].sCapHeight
TEXT = "Subvera"
names = [cmap[ord(c)] for c in TEXT]


def layout(track):
    x, out = 0, []
    for n in names:
        out.append((n, x))
        x += hmtx[n][0] + track
    return out


def ink(track):
    bp = BoundsPen(gs)
    for n, x in layout(track):
        gs[n].draw(TransformPen(bp, (1, 0, 0, 1, x, 0)))
    return bp.bounds  # xMin, yMin, xMax, yMax (font units, y up)


# Track so the ink aspect matches the original wordmark (1727 x 332 px in the 2400px lockup).
TARGET = 1727 / 332
b0 = ink(0)
h = b0[3] - b0[1]
track = (TARGET * h - (b0[2] - b0[0])) / (len(names) - 1)
xmin, ymin, xmax, ymax = ink(track)

# ---------- lockup layout (font units, y down) ----------
D = 1.25 * cap  # disc: 1.25x cap height (was ~1.5x)
GAP = 0.34 * D
word_x = D + GAP - xmin
base_y = 0  # baseline at y=0, so caps sit at -cap
disc_cy = -cap / 2
top = min(disc_cy - D / 2, -ymax)
bottom = max(disc_cy + D / 2, -ymin)
W = word_x + xmax
H = bottom - top

pen = SVGPathPen(gs)
for n, x in layout(track):
    gs[n].draw(TransformPen(pen, (1, 0, 0, -1, word_x + x, -top)))  # flip y, shift so top = 0
word_d = pen.getCommands()

r = lambda v: round(v, 2)
geom = {
    "viewBox": [0, 0, r(W), r(H)],
    "disc": {"cx": r(D / 2), "cy": r(disc_cy - top), "r": r(D / 2)},
    "markScale": r(D / 100),
    "markOrigin": [0, r(disc_cy - top - D / 2)],
    "wordmark": word_d,
}

# ---------- TypeScript geometry for components/ui/Logo.tsx ----------
def ts_mark(name):
    m = MARKS[name]
    return {"stroke": m["stroke"], "waves": [{"d": wave_d(m, y), "color": c} for y, c in zip(m["ys"], m["colors"])]}

ts = f"""// Generated by scripts/build-logo.py (Space Grotesk Bold wordmark, tide-line mark).
// Edit the generator, not this file, so the SVGs, icons and component stay identical.

export const LOGO_COLORS = {json.dumps({"navy": NAVY, "deep": DEEP, "white": WHITE})} as const;

/** The mark in a 100x100 box. "small" is the icon cut for 24px and below. */
export const MARK = {json.dumps({"full": ts_mark("full"), "small": ts_mark("small")}, indent=2)} as const;

/** The horizontal lockup: disc at 1.25x cap height, gap 0.34x the disc, wordmark tracked to the original. */
export const LOCKUP = {json.dumps(geom, indent=2)} as const;
"""
open(f"{ROOT}/components/ui/logo-geometry.ts", "w").write(ts)

# ---------- standalone SVG files ----------
def mark_svg_body(name, disc_fill, scale=1.0, ox=0, oy=0, size=None):
    m = MARKS[name]
    waves = "".join(
        f'<path d="{wave_d(m, y)}" fill="none" stroke="{c}" stroke-width="{m["stroke"]}" stroke-linecap="round"/>'
        for y, c in zip(m["ys"], m["colors"])
    )
    return f'<g transform="translate({ox} {oy}) scale({scale})"><circle cx="50" cy="50" r="50" fill="{disc_fill}"/>{waves}</g>'


def lockup_svg(word_fill, disc_fill):
    vb = " ".join(map(str, geom["viewBox"]))
    body = mark_svg_body("full", disc_fill, geom["markScale"], *geom["markOrigin"])
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="Subvera"><title>Subvera</title>{body}<path d="{word_d}" fill="{word_fill}"/></svg>\n'


def mark_svg(name, disc_fill):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="Subvera"><title>Subvera</title>{mark_svg_body(name, disc_fill)}</svg>\n'


open(f"{ROOT}/public/brand/subvera-lockup.svg", "w").write(lockup_svg(NAVY, NAVY))
open(f"{ROOT}/public/brand/subvera-lockup-reversed.svg", "w").write(lockup_svg(WHITE, DEEP))
open(f"{ROOT}/public/brand/subvera-mark.svg", "w").write(mark_svg("full", NAVY))
open(f"{ROOT}/public/brand/subvera-mark-small.svg", "w").write(mark_svg("small", NAVY))
open(f"{ROOT}/app/icon.svg", "w").write(mark_svg("small", NAVY))

# ---------- raster rendering (supersampled) ----------
def render_mark(px, name, disc=NAVY, square_bg=None, inset=1.0):
    """Mark at px size. square_bg fills the whole square (for iOS, which masks its own corners)."""
    ss = 8
    big = px * ss
    im = Image.new("RGBA", (big, big), square_bg or (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    s = big / 100 * inset
    o = (big - 100 * s) / 2
    if not square_bg:
        d.ellipse((o, o, o + 100 * s, o + 100 * s), fill=disc)
    m = MARKS[name]
    w = m["stroke"] * s
    for y, c in zip(m["ys"], m["colors"]):
        # Stamp round dabs along the curve, closer together than the stroke is wide. A thick
        # polyline leaves hairline seams at its joints; dabs give a solid stroke with round caps.
        for x, yy in wave_points(m, y, n=240):
            cx, cy = o + x * s, o + yy * s
            d.ellipse((cx - w / 2, cy - w / 2, cx + w / 2, cy + w / 2), fill=c)
    return im.resize((px, px), Image.LANCZOS)


def save_png(im, path):
    """Palette PNG: the icons are a few flat colours, so 256 colours is visually lossless at a fraction of the size."""
    im.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(path, optimize=True)


save_png(render_mark(512, "full"), f"{ROOT}/app/icon.png")
# iOS home screen: full-bleed navy square, iOS rounds the corners itself. Mark slightly inset.
save_png(render_mark(180, "full", square_bg=NAVY, inset=0.86), f"{ROOT}/app/apple-icon.png")

# ---------- previews: old vs new at real sizes ----------
sizes = [16, 20, 24, 28, 32, 48]
pad, scale = 12, 6
def strip(images):
    W_ = sum(i.width for i in images) + pad * (len(images) + 1)
    c = Image.new("RGBA", (W_, max(i.height for i in images) + 2 * pad), (255, 255, 255, 255))
    x = pad
    for i in images:
        c.alpha_composite(i, (x, pad + (max(j.height for j in images) - i.height) // 2)); x += i.width + pad
    return c
new = strip([render_mark(s, "small" if s <= 24 else "full") for s in sizes])
new.resize((new.width * scale, new.height * scale), Image.NEAREST).save(f"{S}/new-sizes.png")
print(json.dumps({"track": round(track, 1), "upm": upm, "cap": cap, "viewBox": geom["viewBox"], "aspect": round(W / H, 4)}))
